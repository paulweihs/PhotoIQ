// ── ExclusionRule model ───────────────────────────────────────────────────────

/// <summary>Tests for the ExclusionRule model: folder/path exclusion rules.</summary>
public class ExclusionRuleModelTests
{
    [Fact]
    public void Id_DefaultIsZero_IntKey()
        => Assert.Equal(0, new ExclusionRule().Id);

    [Fact]
    public void Value_DefaultIsEmptyString()
        => Assert.Equal("", new ExclusionRule().Value);

    [Fact]
    public void IsFullPath_DefaultIsFalse()
        => Assert.False(new ExclusionRule().IsFullPath);

    [Fact]
    public void Value_CanBeSet()
    {
        var rule = new ExclusionRule { Value = @"C:\Windows\Temp" };
        Assert.Equal(@"C:\Windows\Temp", rule.Value);
    }

    [Fact]
    public void IsFullPath_CanBeSetToTrue()
    {
        var rule = new ExclusionRule { IsFullPath = true };
        Assert.True(rule.IsFullPath);
    }

    [Fact]
    public void Value_CanStoreUpTo500Characters()
    {
        var longValue = new string('x', 500);
        var rule      = new ExclusionRule { Value = longValue };
        Assert.Equal(500, rule.Value.Length);
    }

    [Theory]
    [InlineData("node_modules", false)]
    [InlineData(@"C:\Users\photos\Private", true)]
    [InlineData(".git", false)]
    [InlineData("Thumbs.db", false)]
    public void IsFullPath_And_Value_RoundTripTogether(string value, bool isFullPath)
    {
        var rule = new ExclusionRule { Value = value, IsFullPath = isFullPath };
        Assert.Equal(value, rule.Value);
        Assert.Equal(isFullPath, rule.IsFullPath);
    }
}

