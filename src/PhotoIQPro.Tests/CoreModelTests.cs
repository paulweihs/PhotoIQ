// ── Tag model ─────────────────────────────────────────────────────────────────

/// <summary>Tests for the Tag model: properties, defaults, and initialization.</summary>
public class TagModelTests
{
    private static Tag Make(string name = "landscape") => new()
    {
        Name           = name,
        NormalizedName = name.ToLowerInvariant(),
    };

    [Fact]
    public void Id_AutoGeneratedAndNotEmpty()
        => Assert.NotEqual(Guid.Empty, Make().Id);

    [Fact]
    public void TwoTags_HaveDifferentIds()
        => Assert.NotEqual(Make().Id, Make().Id);

    [Fact]
    public void Category_DefaultIsGeneral()
        => Assert.Equal(TagCategory.General, Make().Category);

    [Fact]
    public void IsAIGenerated_DefaultIsFalse()
        => Assert.False(Make().IsAIGenerated);

    [Fact]
    public void Confidence_DefaultIsNull()
        => Assert.Null(Make().Confidence);

    [Fact]
    public void Color_DefaultIsNull()
        => Assert.Null(Make().Color);

    [Fact]
    public void DateCreated_DefaultIsRecentUtcTimestamp()
    {
        var before = DateTime.UtcNow.AddSeconds(-2);
        var tag    = Make();
        var after  = DateTime.UtcNow.AddSeconds(2);
        Assert.InRange(tag.DateCreated, before, after);
    }

    [Fact]
    public void MediaFiles_InitialisedToEmptyCollection()
    {
        var tag = Make();
        Assert.NotNull(tag.MediaFiles);
        Assert.Empty(tag.MediaFiles);
    }

    [Fact]
    public void Name_RoundTrips()
    {
        var tag = Make("sunset");
        Assert.Equal("sunset", tag.Name);
    }

    [Fact]
    public void NormalizedName_RoundTrips()
    {
        var tag = Make("Forest");
        Assert.Equal("forest", tag.NormalizedName);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void IsAIGenerated_CanBeSetToEitherValue(bool value)
    {
        var tag = Make();
        tag.IsAIGenerated = value;
        Assert.Equal(value, tag.IsAIGenerated);
    }

    [Fact]
    public void Confidence_CanBeSetToDoubleValue()
    {
        var tag = Make();
        tag.Confidence = 0.87;
        Assert.Equal(0.87, tag.Confidence);
    }

    [Fact]
    public void Color_CanBeSet()
    {
        var tag = Make();
        tag.Color = "#FF5733";
        Assert.Equal("#FF5733", tag.Color);
    }

    [Theory]
    [InlineData(TagCategory.Object)]
    [InlineData(TagCategory.Scene)]
    [InlineData(TagCategory.Activity)]
    [InlineData(TagCategory.Color)]
    [InlineData(TagCategory.Style)]
    [InlineData(TagCategory.Emotion)]
    [InlineData(TagCategory.Person)]
    public void Category_CanBeSetToNonDefaultValues(TagCategory cat)
    {
        var tag = Make();
        tag.Category = cat;
        Assert.Equal(cat, tag.Category);
    }
}

