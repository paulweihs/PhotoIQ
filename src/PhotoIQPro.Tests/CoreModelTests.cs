    [Fact]
    public void FileFormat_DefaultIsEmptyString()
        => Assert.Equal("", Make().FileFormat);

    [Fact]
    public void GpuUsed_DefaultIsFalse()
        => Assert.False(Make().GpuUsed);

    [Fact]
    public void NumericFields_DefaultToZero()
    {
        var m = Make();
        Assert.Equal(0, m.ImageWidth);
        Assert.Equal(0, m.ImageHeight);
        Assert.Equal(0L, m.FileSizeBytes);
        Assert.Equal(0L, m.PreprocessingMs);
        Assert.Equal(0L, m.InferenceMs);
        Assert.Equal(0L, m.TotalAnalysisMs);
        Assert.Equal(0, m.TagCount);
        Assert.Equal(0, m.DescriptionLength);
    }

    [Fact]
    public void AnalyzedAt_DefaultIsRecentUtcTimestamp()
    {
        var before = DateTime.UtcNow.AddSeconds(-2);
        var m      = Make();
        var after  = DateTime.UtcNow.AddSeconds(2);
        Assert.InRange(m.AnalyzedAt, before, after);
    }

    [Fact]
    public void AllFields_CanBeSet()
    {
        var photoId = Guid.NewGuid();
        var m = new AnalysisMetric
        {
            PhotoId           = photoId,
            ModelName         = "llama3.2-vision",
            ImageWidth        = 3840,
            ImageHeight       = 2160,
            FileFormat        = "jpg",
            FileSizeBytes     = 4_500_000L,
            PreprocessingMs   = 45L,
            InferenceMs       = 3200L,
            TotalAnalysisMs   = 3250L,
            TagCount          = 12,
            DescriptionLength = 187,
            GpuUsed           = true,
        };

        Assert.Equal(photoId,         m.PhotoId);
        Assert.Equal("llama3.2-vision", m.ModelName);
        Assert.Equal(3840,            m.ImageWidth);
        Assert.Equal(2160,            m.ImageHeight);
        Assert.Equal("jpg",           m.FileFormat);
        Assert.Equal(4_500_000L,      m.FileSizeBytes);
        Assert.Equal(45L,             m.PreprocessingMs);
        Assert.Equal(3200L,           m.InferenceMs);
        Assert.Equal(3250L,           m.TotalAnalysisMs);
        Assert.Equal(12,              m.TagCount);
        Assert.Equal(187,             m.DescriptionLength);
        Assert.True(m.GpuUsed);
    }

    [Fact]
    public void PhotoId_CanBeSetToNonEmptyGuid()
    {
        var id = Guid.NewGuid();
        var m  = new AnalysisMetric { PhotoId = id };
        Assert.Equal(id, m.PhotoId);
    }
